#!/usr/bin/env python3
# Pack the 6805 microcode ROM (6805.uc, 4096 x 39 bits) into a dictionary:
#   jt6805_ucode_idx.hex  4096 x 8-bit index into the word table (one BSRAM pair)
#   jt6805_ucode.v        the ROM module: index ROM + word table in logic
# The microcode has only ~145 distinct words, so this needs 2 BSRAM instead of 10.
# Run from this directory after 6805.uc changes.

import sys

DEPTH, WIDTH = 4096, 39

with open('6805.uc') as f:
    words = [int(l.strip(), 2) for l in f if l.strip()]
if len(words) != DEPTH:
    sys.exit(f'6805.uc has {len(words)} lines, expected {DEPTH}')

# index 0 is the all-zero word so the table's default is a no-op
table = [0]
lookup = {0: 0}
for w in words:
    if w not in lookup:
        lookup[w] = len(table)
        table.append(w)
if len(table) > 256:
    sys.exit(f'{len(table)} distinct words do not fit an 8-bit index')

with open('jt6805_ucode_idx.hex', 'w') as f:
    for w in words:
        f.write(f'{lookup[w]:02x}\n')

with open('jt6805_ucode.v', 'w') as f:
    f.write(f'''// Generated by ucode_pack.py from 6805.uc. Do not edit.
//
// 6805 microcode ROM, {DEPTH} x {WIDTH} bits, stored as an 8-bit index ROM
// (block RAM) into a table of the {len(table)} distinct words (logic).
// Same timing as the Gowin pROM it replaces: dout follows ad by one clock.

module jt6805_ucode(
    input             clk,
    input      [11:0] ad,
    output     [{WIDTH-1}:0] dout
);

reg [7:0] idx_rom[0:{DEPTH-1}] /* synthesis syn_romstyle = "block_rom" */;
reg [7:0] idx;

// The word table must stay logic. Left alone, synthesis merges it with the
// decode logic after it into a second clocked ROM, which adds a clock.
reg [{WIDTH-1}:0] word /* synthesis syn_romstyle = "logic" syn_keep = 1 */;
assign dout = word;

initial $readmemh("jt6805_ucode_idx.hex", idx_rom);

always @(posedge clk) idx <= idx_rom[ad];

always @* begin
    case(idx)
''')
    for i, w in enumerate(table):
        f.write(f"        8'd{i}: word = {WIDTH}'h{w:010x};\n")
    f.write(f'''        default: word = {WIDTH}'h0;
    endcase
end

endmodule
''')

print(f'{len(table)} distinct words, index ROM {DEPTH} x 8')
